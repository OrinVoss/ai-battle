/* config 里选手 emoji -> 头像图标映射；未知 emoji 用 robot 兜底 */
const AVATAR_ICONS = {
  "🕸️": "web", "🕸": "web",
  "🎭": "mask",
  "🔪": "knife",
  "👑": "crown",
  "🐿️": "acorn", "🐿": "acorn",
  "🥀": "rose",
  "🤖": "robot",
};
function avatarIconName(emoji) {
  return AVATAR_ICONS[String(emoji == null ? "" : emoji).trim()] || "robot";
}

/* 返回内联 SVG 字符串；size 传像素数，颜色继承 currentColor */
function icon(name, size = 16) {
  const paths = ICON_PATHS[name] || ICON_PATHS.robot;
  const d = paths.map(p => `<path d="${p}"/>`).join("");
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${d}</svg>`;
}

/* canvas 绘制：Path2D 缓存，按 icon 的 24 坐标系等比缩放 */
const _p2dCache = {};
function drawIcon(ctx, name, cx, cy, size, color, alpha) {
  let p = _p2dCache[name];
  if (!p) {
    p = new Path2D((ICON_PATHS[name] || ICON_PATHS.robot).join(" "));
    _p2dCache[name] = p;
  }
  ctx.save();
  ctx.translate(cx, cy);
  ctx.scale(size / 24, size / 24);
  ctx.translate(-12, -12);
  if (alpha != null) ctx.globalAlpha = alpha;
  ctx.strokeStyle = color;
  ctx.lineWidth = 2;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  ctx.stroke(p);
  ctx.restore();
}

/* HTML 静态占位：<i class="ic" data-icon="play" data-size="14"></i> 在水合时替换为内联 SVG */
(function hydrateIcons() {
  document.querySelectorAll("[data-icon]").forEach(el => {
    el.innerHTML = icon(el.dataset.icon, parseInt(el.dataset.size || "15", 10));
  });
})();
